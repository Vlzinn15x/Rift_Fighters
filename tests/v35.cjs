'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const pub=path.resolve(__dirname,'../public');
const read=name=>fs.readFileSync(path.join(pub,name),'utf8');
const script=read('v35.js');
const html=read('index.html');
new vm.Script(script,{filename:'v35.js'});
assert(html.indexOf('v35.js?v=35.1')>html.indexOf('upgrades.js?v=34-settings'),'V35 must load after V34 state');
assert(html.includes('v35.css?v=35.1'));
const game=read('game.js');
assert(game.includes('window.RiftV35?.aiTick'),'CPU hook must be installed');
assert(game.includes('window.matchMedia?.(\'(pointer:coarse)\')?.matches?1:2'),'mobile canvas optimization');
const block=script.slice(script.indexOf('  const bosses = ['),script.indexOf('  const sanitize = raw =>'));
const getDefinitions=vm.runInNewContext(`(()=>{${block}\nreturn {bosses,auras};})()`);
const {bosses,auras}=getDefinitions;
assert.equal(bosses.length,5);
assert.equal(new Set(bosses.map(b=>b.name)).size,5);
assert(bosses.every(b=>b.fighter>=0&&b.fighter<=10&&b.mult>1&&b.reward>0));
assert.equal(auras.length,5);
assert(auras.every(a=>a.id&&a.price>=0&&/^#[a-f\d]{6}$/i.test(a.color)));
const a=script.indexOf('  const sanitize = raw =>');
const b=script.indexOf('  let progress;',a);
const sanitize=vm.runInNewContext(`(()=>{${block}${script.slice(a,b)}\nreturn sanitize;})()`);
const clean=sanitize({coins:Infinity,unlocked:99,bossWins:[true,false,true],owned:['void','unknown','void'],equipped:'unknown',totalDamage:-90,bestCombo:5.9});
assert.equal(clean.coins,0);assert.equal(clean.unlocked,5);assert.equal(clean.bossWins.length,5);
assert.equal(clean.bestCombo,5);assert.equal(clean.totalDamage,0);assert.equal(clean.equipped,'classic');
assert.equal(clean.owned.filter(x=>x==='void').length,1);
const empty=sanitize(null);assert.equal(empty.unlocked,1);assert.equal(empty.coins,0);
assert.equal(empty.bossWins.filter(Boolean).length,0);
const files=[...html.matchAll(/(?:src|href)="([^"?]+)(?:\?[^\"]+)?"/g)].map(x=>x[1]).filter(x=>!x.startsWith('#'));
for(const f of files){if(f==='')continue;assert(fs.existsSync(path.join(pub,f)),`Missing HTML asset ${f}`);}
assert(fs.existsSync(path.resolve(__dirname,'../.github/workflows/pages.yml')),'GitHub Pages workflow');
console.log('PASS: V35 static resources, five bosses, CPU hook, mobile scaling, purchase data, storage sanitization and GitHub Pages workflow');
